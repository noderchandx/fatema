-- ---------- বিষয় (শ্রেণি অনুযায়ী) ----------
create table if not exists public.subjects (
  id         bigint generated always as identity primary key,
  class_id   bigint not null references public.classes(id) on delete cascade,
  name       text not null,
  full_marks numeric not null default 100 check (full_marks > 0),
  sort_order int not null default 0,
  unique (class_id, name)
);

-- ---------- শিক্ষার্থী (আইডি স্বয়ংক্রিয়, ১০০০ থেকে শুরু) ----------
create table if not exists public.students (
  id           bigint generated by default as identity (start with 1000) primary key,
  name         text not null,
  roll         int  not null,
  father_name  text not null,
  mother_name  text not null,
  birth_reg_no text,
  dob          date,
  gender       text not null check (gender in ('male','female')),
  class_id     bigint not null references public.classes(id) on delete restrict,
  photo_url    text,
  status       text not null default 'active' check (status in ('active','passed_out')),
  verify_token uuid not null default gen_random_uuid() unique,
  created_at   timestamptz not null default now()
);
create index if not exists students_class_idx on public.students(class_id);

