-- =====================================================================
-- Row Level Security: শুধু অ্যাডমিন সব টেবিল পড়তে/লিখতে পারবে
-- =====================================================================
do $$
declare t text;
begin
  foreach t in array array['settings','classes','subjects','students','teachers','exams','results','promotions']
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "admin all" on public.%I', t);
    execute format(
      'create policy "admin all" on public.%I for all to authenticated using (public.is_admin()) with check (public.is_admin())',
      t
    );
  end loop;
end $$;

alter table public.admins enable row level security;
drop policy if exists "read own admin row" on public.admins;
create policy "read own admin row" on public.admins
  for select to authenticated using (user_id = auth.uid());

