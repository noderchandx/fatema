-- কিউআর যাচাই: লগইন ছাড়াই (শুধু গোপন টোকেন জানলে) সীমিত তথ্য দেখা যাবে
-- আইডি অনুমান করে তথ্য বের করা যাবে না, কারণ টোকেন র‍্যান্ডম UUID।
-- =====================================================================
create or replace function public.verify_student(p_token uuid)
returns json
language sql
security definer
stable
set search_path = public
as $$
  select json_build_object(
    'student_id', s.id,
    'name',       s.name,
    'roll',       s.roll,
    'father',     s.father_name,
    'class',      c.name,
    'photo_url',  s.photo_url,
    'status',     s.status,
    'madrasa',    (select value from public.settings where key = 'madrasa_name'),
    'address',    (select value from public.settings where key = 'madrasa_address')
  )
  from public.students s
  left join public.classes c on c.id = s.class_id
  where s.verify_token = p_token;
$$;

revoke all on function public.verify_student(uuid) from public;
grant execute on function public.verify_student(uuid) to anon, authenticated;
